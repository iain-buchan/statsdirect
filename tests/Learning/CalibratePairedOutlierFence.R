# Run from the repository root:
# Rscript --vanilla tests/Learning/CalibratePairedOutlierFence.R
# Add --verify to check the generated C# against the CSV and test the rates.

csv_path <- "tests/Learning/paired-outlier-fence.csv"
csharp_path <- "StatsDirectUI/UI/PairedOutlierFence.cs"
pair_counts <- 8:100

fence_ratio <- function(minimum, lower, upper, maximum) {
  pmax(lower - minimum, maximum - upper) / (upper - lower)
}

calibrate <- function(n, simulations) {
  positions <- c(0.25, 0.75) * (n + 1)
  lower_rank <- floor(positions)
  upper_rank <- ceiling(positions)
  ranks <- sort(unique(c(1, lower_rank, upper_rank, n)))

  # The probability integral transform maps normal order statistics to
  # uniform order statistics. Given U_(i), the remaining n-i observations
  # are ordered uniforms above U_(i). Draw only the ranks needed for the
  # type-6 quartiles and extremes, then transform them back to normal values.
  u <- numeric(simulations)
  previous <- 0
  values <- matrix(0, nrow = simulations, ncol = length(ranks))
  for (column in seq_along(ranks)) {
    rank <- ranks[column]
    u <- u + (1 - u) * rbeta(simulations, rank - previous, n + 1 - rank)
    values[, column] <- qnorm(u)
    previous <- rank
  }
  quartile <- function(i) {
    lo <- values[, match(lower_rank[i], ranks)]
    hi <- values[, match(upper_rank[i], ranks)]
    lo + (positions[i] - lower_rank[i]) * (hi - lo)
  }
  statistic <- fence_ratio(values[, 1], quartile(1), quartile(2), values[, ncol(values)])
  quantile(statistic, 0.95, type = 7, names = FALSE)
}

csharp_lines <- function(multipliers) {
  rows <- vapply(split(multipliers, (seq_along(multipliers) - 1L) %/% 4L),
                 function(row) paste0("        ", paste(row, collapse = ", "), ","), "")
  c("// Generated by tests/Learning/CalibratePairedOutlierFence.R.",
    "// A 5% sample-level warning rate under normality, using type-6 quartiles.",
    "using System;",
    "",
    "namespace StatsDirect.UI;",
    "",
    "internal static class PairedOutlierFence",
    "{",
    "    internal const int MinimumPairs = 8;",
    "",
    "    internal static double Multiplier(int count) => Multipliers[count - MinimumPairs];",
    "",
    "    private static ReadOnlySpan<double> Multipliers =>",
    "    [",
    unname(rows),
    "    ];",
    "}")
}

RNGkind("Mersenne-Twister", "Inversion", "Rejection")
args <- commandArgs(trailingOnly = TRUE)
if (!length(args)) {
  set.seed(20261127)
  multipliers <- sprintf("%.12f", vapply(pair_counts, calibrate, 0, simulations = 1000000L))
  writeLines(c("pairs,multiplier", paste(pair_counts, multipliers, sep = ",")), csv_path)
  writeLines(csharp_lines(multipliers), csharp_path)
} else if (identical(args, "--verify")) {
  table <- read.csv(csv_path, colClasses = c("integer", "character"))
  stopifnot(identical(table$pairs, pair_counts),
            identical(readLines(csharp_path), csharp_lines(table$multiplier)))

  # An independent simulation draws whole samples directly, then uses R's
  # type-6 quantile calculation to check the 5% target.
  set.seed(20261128)
  trials <- 20000L
  for (n in c(10L, 30L, 50L, 100L)) {
    statistics <- replicate(trials, {
      x <- rnorm(n)
      quartiles <- quantile(x, c(0.25, 0.75), type = 6, names = FALSE)
      fence_ratio(min(x), quartiles[1], quartiles[2], max(x))
    })
    multiplier <- as.numeric(table$multiplier[table$pairs == n])
    rate <- mean(statistics > multiplier)
    cat(sprintf("n = %3d, multiplier = %.4f, warning rate = %.2f%%\n", n, multiplier, 100 * rate))
    stopifnot(abs(rate - 0.05) <= 0.01)
  }
} else {
  stop("Expected no arguments or --verify.")
}
